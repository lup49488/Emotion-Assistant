def localize_status_text(text: str, locale: str | None) -> str:
    localized = str(text)
    if str(locale or "").lower().startswith("en"):
        replacement_map = dict(EN_STATUS_PHRASES)
    else:
        if re.search(r"[\u4e00-\u9fff]", localized):
            return localized
        replacement_map = {target: source for source, target in EN_STATUS_PHRASES.items()}
    pattern = re.compile(
        "|".join(re.escape(source) for source in sorted(replacement_map, key=len, reverse=True))
    )
    return pattern.sub(lambda match: replacement_map[match.group(0)], localized)
